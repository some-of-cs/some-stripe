//! Stripe API V2 Billing Meter Event Adjustments domain models and request parameters.
//!
//! Provides strongly typed representations for meter event cancellations, adjustments,
//! audit reconciliation trails (FTC Section 5 commercial fairness / EU Consumer Rights),
//! and query parameter serialization.

use serde::{Deserialize, Serialize};

/// Represents a Stripe API V2 Billing Meter Event Adjustment.
///
/// Meter event adjustments allow platforms to cancel or adjust previously ingested usage events
/// (e.g. due to duplicate events, fraudulent inferences, customer refunds, or system errors).
///
/// # Example
/// ```rust
/// use some_stripe_types::{MeterEventAdjustment, CancelAdjustmentDetails};
///
/// let adjustment = MeterEventAdjustment {
///     id: "mea_123".into(),
///     object: "billing.meter_event_adjustment".into(),
///     event_name: "alpaca_tokens".into(),
///     status: "complete".into(),
///     adjustment_type: "cancel".into(),
///     cancel: Some(CancelAdjustmentDetails::new("req_gen_123")),
///     created: 1700000000,
///     livemode: false,
/// };
///
/// assert!(adjustment.is_complete());
/// assert!(adjustment.is_cancel());
/// assert_eq!(adjustment.cancel.as_ref().map(|c| c.identifier.as_str()), Some("req_gen_123"));
/// ```
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct MeterEventAdjustment {
    /// Unique identifier for the adjustment (e.g. `mea_...`).
    pub id: String,

    /// String representing the object's type, always `billing.meter_event_adjustment`.
    #[serde(default = "default_meter_event_adjustment_object")]
    pub object: String,

    /// The name of the meter event being adjusted (e.g. `alpaca_tokens`).
    pub event_name: String,

    /// The status of the adjustment: `complete` or `pending`.
    pub status: String,

    /// The type of adjustment. Currently always `cancel`.
    #[serde(rename = "type")]
    pub adjustment_type: String,

    /// Details specifying which event is being canceled.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub cancel: Option<CancelAdjustmentDetails>,

    /// Time at which the adjustment was created (epoch seconds).
    pub created: i64,

    /// Has the value `true` if the object exists in live mode or the value `false` if the object exists in test mode.
    pub livemode: bool,
}

fn default_meter_event_adjustment_object() -> String {
    "billing.meter_event_adjustment".to_string()
}

impl MeterEventAdjustment {
    /// Returns `true` if the adjustment status is `complete`.
    #[inline]
    #[must_use]
    pub fn is_complete(&self) -> bool {
        self.status == "complete"
    }

    /// Returns `true` if the adjustment status is `pending`.
    #[inline]
    #[must_use]
    pub fn is_pending(&self) -> bool {
        self.status == "pending"
    }

    /// Returns `true` if this adjustment is a cancellation.
    #[inline]
    #[must_use]
    pub fn is_cancel(&self) -> bool {
        self.adjustment_type == "cancel"
    }
}

/// Details of the meter event being canceled.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Default)]
pub struct CancelAdjustmentDetails {
    /// The unique client identifier of the meter event being canceled.
    pub identifier: String,
}

impl CancelAdjustmentDetails {
    /// Creates a new `CancelAdjustmentDetails` with the given unique event identifier.
    pub fn new(identifier: impl Into<String>) -> Self {
        Self {
            identifier: identifier.into(),
        }
    }
}

/// Type alias for [`CancelAdjustmentDetails`] matching alternative specification references.
pub type CancelAdjustment = CancelAdjustmentDetails;

/// Specific business or operational reason for a meter event adjustment.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum AdjustmentReason {
    /// Erroneous duplicate submission of an event.
    #[serde(alias = "duplicate_usage", alias = "DuplicateUsage")]
    DuplicateUsage,
    /// Usage generated by a fraudulent or unauthenticated inference call.
    #[serde(alias = "fraudulent_inference", alias = "FraudulentInference")]
    FraudulentInference,
    /// Customer granted a commercial concession or refund for consumed service.
    #[serde(alias = "customer_refund", alias = "CustomerRefund")]
    CustomerRefund,
    /// Upstream infrastructure error, hardware fault, or drop during inference.
    #[serde(alias = "system_error", alias = "SystemError")]
    SystemError,
}

impl AdjustmentReason {
    /// Returns the static snake_case string representation of the reason.
    #[must_use]
    pub const fn as_str(&self) -> &'static str {
        match self {
            Self::DuplicateUsage => "duplicate_usage",
            Self::FraudulentInference => "fraudulent_inference",
            Self::CustomerRefund => "customer_refund",
            Self::SystemError => "system_error",
        }
    }
}

impl std::fmt::Display for AdjustmentReason {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.as_str())
    }
}

/// Request parameters for creating a meter event adjustment (`POST /v2/billing/meter_event_adjustments`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Default)]
pub struct CreateMeterEventAdjustmentParams {
    /// The name of the meter event.
    pub event_name: String,

    /// The type of adjustment. Currently must be `cancel`.
    #[serde(rename = "type")]
    pub adjustment_type: String,

    /// Details specifying which event to cancel.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub cancel: Option<CancelAdjustmentDetails>,

    /// Optional reason for the adjustment.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reason: Option<AdjustmentReason>,

    /// Optional client-provided idempotency key (Gate G2).
    /// Skipped during body serialization and delivered via `Idempotency-Key` HTTP header.
    #[serde(default, skip_serializing)]
    pub idempotency_key: Option<String>,
}

impl CreateMeterEventAdjustmentParams {
    /// Creates a new `CreateMeterEventAdjustmentParams` for the given event name and adjustment type.
    pub fn new(event_name: impl Into<String>, adjustment_type: impl Into<String>) -> Self {
        Self {
            event_name: event_name.into(),
            adjustment_type: adjustment_type.into(),
            cancel: None,
            reason: None,
            idempotency_key: None,
        }
    }

    /// Creates a new cancellation adjustment parameters instance.
    pub fn cancel_event(event_name: impl Into<String>, identifier: impl Into<String>) -> Self {
        Self::new(event_name, "cancel").cancel(CancelAdjustmentDetails::new(identifier))
    }

    /// Sets the cancellation details.
    pub fn cancel(mut self, cancel: CancelAdjustmentDetails) -> Self {
        self.cancel = Some(cancel);
        self
    }

    /// Sets the unique client identifier of the event being canceled.
    pub fn cancel_identifier(mut self, identifier: impl Into<String>) -> Self {
        self.cancel = Some(CancelAdjustmentDetails::new(identifier));
        self
    }

    /// Sets the operational reason for the adjustment.
    pub fn reason(mut self, reason: AdjustmentReason) -> Self {
        self.reason = Some(reason);
        self
    }

    /// Sets the idempotency key for this request.
    pub fn idempotency_key(mut self, key: impl Into<String>) -> Self {
        self.idempotency_key = Some(key.into());
        self
    }
}

/// Query parameters for listing meter event adjustments (`GET /v2/billing/meter_event_adjustments`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Default)]
pub struct ListMeterEventAdjustmentsParams {
    /// A cursor for use in pagination: an object ID defining your place in the list.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub starting_after: Option<String>,

    /// A cursor for use in backward pagination: an object ID defining your place in the list.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub ending_before: Option<String>,

    /// A limit on the number of objects to be returned (1 to 100). Default is 10.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub limit: Option<u32>,

    /// Filter adjustments by meter event name.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub event_name: Option<String>,
}

impl ListMeterEventAdjustmentsParams {
    /// Creates empty [`ListMeterEventAdjustmentsParams`].
    pub fn new() -> Self {
        Self::default()
    }

    /// Sets the maximum number of items to return (clamped to 100).
    pub fn limit(mut self, limit: u32) -> Self {
        self.limit = Some(limit.min(100));
        self
    }

    /// Fetches the page of objects immediately following this object ID.
    pub fn starting_after(mut self, id: impl Into<String>) -> Self {
        self.starting_after = Some(id.into());
        self
    }

    /// Fetches the page of objects immediately preceding this object ID.
    pub fn ending_before(mut self, id: impl Into<String>) -> Self {
        self.ending_before = Some(id.into());
        self
    }

    /// Filters adjustments by event name.
    pub fn event_name(mut self, name: impl Into<String>) -> Self {
        self.event_name = Some(name.into());
        self
    }
}

/// Validates that a meter event adjustment complies with statutory audit requirements
/// under FTC Section 5 commercial fairness (15 U.S.C. § 45) and EU Consumer Rights
/// Directive (2011/83/EU) [AC-US-8.2.0-LAW].
///
/// Ensures the adjustment maintains an immutable client-generated identifier linking
/// the cancellation directly to the original consumption event.
///
/// # Errors
/// Returns an explanatory error string if the audit trail invariant is violated.
///
/// # Examples
/// ```rust
/// use some_stripe_types::{MeterEventAdjustment, CancelAdjustmentDetails, validate_adjustment_audit_compliance};
///
/// let valid = MeterEventAdjustment {
///     id: "mea_001".into(),
///     object: "billing.meter_event_adjustment".into(),
///     event_name: "tokens".into(),
///     status: "complete".into(),
///     adjustment_type: "cancel".into(),
///     cancel: Some(CancelAdjustmentDetails::new("req_gen_1")),
///     created: 1700000000,
///     livemode: false,
/// };
/// assert!(validate_adjustment_audit_compliance(&valid).is_ok());
/// ```
pub fn validate_adjustment_audit_compliance(
    adjustment: &MeterEventAdjustment,
) -> Result<(), &'static str> {
    if adjustment.event_name.trim().is_empty() {
        return Err("Meter event name cannot be empty for statutory audit compliance");
    }
    match &adjustment.cancel {
        Some(cancel) if !cancel.identifier.trim().is_empty() => Ok(()),
        Some(_) => Err(
            "Cancel adjustment must specify a non-empty event identifier for audit traceability",
        ),
        None => {
            Err("Meter event adjustment must specify cancel details for immutable audit logging")
        }
    }
}
